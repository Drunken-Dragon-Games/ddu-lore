#!/usr/bin/env node
// Builds tools/web/data/norsund.json and the generated dictionary docs from the YAML records.
//   node build.mjs            (from tools/)
import fs from 'node:fs';
import path from 'node:path';
import { REPO_ROOT, loadFiles, buildData } from './norsund/node.js';
import { setData } from './norsund/data.js';
import { validateFiles, formatReport } from './norsund/validate.js';
import { ipa, respell } from './norsund/phonology.js';
import { nounForms, verbForms, adjForms, pronounForms } from './norsund/morphology.js';
import { sortEntries, initialLetter, normalizeGloss } from './norsund/lexicon.js';

const OUT_JSON = path.join(REPO_ROOT, 'tools/web/data/norsund.json');
const OUT_DICT = path.join(REPO_ROOT, 'docs/languages/norsund/dictionary.md');
const OUT_INDEX = path.join(REPO_ROOT, 'docs/languages/norsund/english-index.md');

const POS_LABEL = { noun: 'n.', verb: 'v.', adj: 'adj.', adv: 'adv.', pron: 'pron.', det: 'det.', prep: 'prep.', conj: 'conj.',
  part: 'particle', num: 'num.', interj: 'interj.', affix: 'affix', name: 'name' };
const LAYER_LABEL = { kedre: 'Kedre loan', 'kedre-learned': 'learned Kedre loan', 'old-norsund': 'Old Norsund', foreign: 'foreign', 'proto-valian': 'Proto-Valian' };

function esc(s) {
  return String(s).replace(/([*_`\\[\]<>|])/g, '\\$1');
}

function safe(fn, fallback = '') {
  try { return fn(); } catch { return fallback; }
}

function formsLine(e) {
  if (e.lemma.includes(' ')) return '';
  if (e.pos === 'noun' || (e.pos === 'name' && e.class && !/['’]/.test(e.lemma))) {
    if (e.pos === 'name') return '';
    const f = safe(() => nounForms(e), null);
    if (!f) return '';
    return `pl. ${f.pl}; the: ${f.def}, ${f.defpl}`;
  }
  if (e.pos === 'verb') {
    const f = safe(() => verbForms(e), null);
    if (!f || f.invariable) return '';
    return `${f.prs}, ${f.pst}, ${f.ptcp}`;
  }
  if (e.pos === 'adj') {
    const f = safe(() => adjForms(e), null);
    return f ? `${f.cmpr}, ${f.supl}; adv. ${f.adv}` : '';
  }
  if (e.pos === 'pron') {
    const f = pronounForms(e);
    return [f.object !== e.lemma ? `obj. ${f.object}` : '', f.possessive ? `poss. ${f.possessive}` : ''].filter(Boolean).join(', ');
  }
  return '';
}

function classLabel(e) {
  if (e.pos === 'noun') return e.class === 'animate' ? 'n. an.' : 'n. inan.';
  if (e.pos === 'verb') return e.class && e.class !== 'weak' ? `v. (${e.class})` : 'v.';
  return POS_LABEL[e.pos] || e.pos;
}

function tags(e) {
  const t = [];
  if (e.layer && LAYER_LABEL[e.layer]) t.push(LAYER_LABEL[e.layer]);
  if (e.register && e.register !== 'common') t.push(e.register);
  if (e.tier === 'sandbox') t.push('sandbox');
  if (e.status === 'proposed') t.push('proposed');
  return t.length ? ` [${t.join(', ')}]` : '';
}

function dictionaryMarkdown(data) {
  const entries = sortEntries(data.dictionary.entries);
  const byId = new Map(entries.map((e) => [e.id, e]));
  const lines = [];
  lines.push('# Norsund dictionary', '');
  lines.push(`> Generated by \`tools/build.mjs\` from \`records/languages/norsund/dictionary/*.yaml\`. Do not edit this file by hand; edit the YAML and run \`node build.mjs\` in \`tools/\`.`);
  lines.push(`> Version ${data.version} · ${entries.length} entries.`, '');
  lines.push('**How to read an entry:** headword, pronunciation in IPA, part of speech (n. an. = animate noun, n. inan. = inanimate noun), the English meanings, then the main forms (plural and definite forms for nouns; present, past and participle for verbs; comparative, superlative and adverb for adjectives), the etymology, and where the word appears in canon names. Words built from another entry point back to it with ←.', '');
  lines.push('**Alphabet:** a b d e f g gj h i j k kj l m n ng o p r s t th u v w y. The digraphs gj, kj, ng and th are letters of their own, so *kjold* comes after *kyr*.', '');
  let letter = null;
  for (const e of entries) {
    const L = initialLetter(e.lemma) || '?';
    if (L !== letter) { letter = L; lines.push('', `## ${L.toUpperCase()}`, ''); }
    const pron = safe(() => ipa(e.lemma, { parts: e.parts, layer: e.layer }), '');
    const forms = formsLine(e);
    const parent = e.parent && byId.get(e.parent) ? ` ← *${esc(byId.get(e.parent).lemma)}*` : '';
    const parts = [`**${esc(e.lemma)}**`];
    if (pron && !/['’]/.test(e.lemma)) parts.push(`/${pron}/`);
    parts.push(`*${classLabel(e)}*${tags(e)}`);
    let line = `${parts.join(' ')} — ${esc(e.gloss.join('; '))}.`;
    if (forms) line += ` ${esc(forms)}.`;
    if (e.parts && e.parts.length) line += ` (${esc(e.parts.join(' + '))})`;
    if (e.etymology) line += ` *From* ${esc(e.etymology)}.`;
    if (e.attested && e.attested.length) line += ` *In:* ${esc(e.attested.join(', '))}.`;
    if (e.notes) line += ` ${esc(e.notes)}`;
    line += parent;
    lines.push(`- ${line}`);
  }
  lines.push('');
  return lines.join('\n');
}

function englishIndexMarkdown(data) {
  const map = new Map();
  for (const e of data.dictionary.entries) {
    for (const g of e.gloss) {
      const key = normalizeGloss(g);
      if (!key || /^[A-Z.]+$/.test(String(g).split(' ')[0])) continue;
      if (!map.has(key)) map.set(key, []);
      const list = map.get(key);
      if (!list.some((x) => x.id === e.id)) list.push(e);
    }
  }
  const keys = [...map.keys()].sort((a, b) => a.localeCompare(b, 'en'));
  const lines = ['# English–Norsund index', '',
    `> Generated by \`tools/build.mjs\`. ${keys.length} English keywords. For full entries see [dictionary.md](dictionary.md).`, ''];
  let letter = null;
  for (const k of keys) {
    const L = (k[0] || '?').toUpperCase();
    if (L !== letter) { letter = L; lines.push('', `## ${L}`, ''); }
    const list = map.get(k).map((e) => `**${esc(e.lemma)}** *${classLabel(e)}*${tags(e)}`).join(', ');
    lines.push(`- ${esc(k)}: ${list}`);
  }
  lines.push('');
  return lines.join('\n');
}

// The browser workbench (tools/web) must be self-contained: it gets its own copy of the browser-safe engine modules
// (everything in tools/norsund except node.js), and artifact.html is index.html without the document wrapper tags.
const WEB_DIR = path.join(REPO_ROOT, 'tools/web');
const ENGINE_DIR = path.join(REPO_ROOT, 'tools/norsund');

export function buildWeb() {
  const outDir = path.join(WEB_DIR, 'norsund');
  fs.rmSync(outDir, { recursive: true, force: true });
  fs.mkdirSync(outDir, { recursive: true });
  const copied = [];
  for (const f of fs.readdirSync(ENGINE_DIR).sort()) {
    if (!f.endsWith('.js') || f === 'node.js') continue;
    const src = fs.readFileSync(path.join(ENGINE_DIR, f), 'utf8');
    fs.writeFileSync(path.join(outDir, f), `// Copied from tools/norsund/${f} by tools/build.mjs. Edit the original, then run node build.mjs.\n${src}`);
    copied.push(f);
  }
  const html = fs.readFileSync(path.join(WEB_DIR, 'index.html'), 'utf8');
  const part = (a, b) => {
    const i = html.indexOf(a), j = html.indexOf(b);
    if (i < 0 || j < 0 || j < i) throw new Error(`tools/web/index.html is missing the ${a} / ${b} markers`);
    return html.slice(i + a.length, j).trim();
  };
  const head = part('<!-- artifact:begin -->', '<!-- artifact:head-end -->');
  const body = part('<!-- artifact:body-begin -->', '<!-- artifact:end -->');
  fs.writeFileSync(path.join(WEB_DIR, 'artifact.html'),
    `${head}\n<!-- Generated from tools/web/index.html by tools/build.mjs: the same page without the document wrapper, for publishing as an Artifact. Edit index.html, not this file. -->\n${body}\n`);
  return copied;
}

export function build({ quiet = false } = {}) {
  const files = loadFiles(REPO_ROOT);
  const report = validateFiles(files);
  const data = buildData(files);
  setData(data);
  for (const e of data.dictionary.entries) {
    if (!/['’]/.test(e.lemma)) {
      e.ipa = safe(() => ipa(e.lemma, { parts: e.parts, layer: e.layer }), '');
      e.respell = safe(() => respell(e.lemma, { parts: e.parts, layer: e.layer }), '');
    }
  }
  data.builtFrom = files.map((f) => f.path);
  data.validation = { errors: report.errors.length, warnings: report.warnings.length };
  fs.mkdirSync(path.dirname(OUT_JSON), { recursive: true });
  fs.writeFileSync(OUT_JSON, JSON.stringify(data));
  fs.mkdirSync(path.dirname(OUT_DICT), { recursive: true });
  fs.writeFileSync(OUT_DICT, dictionaryMarkdown(data));
  fs.writeFileSync(OUT_INDEX, englishIndexMarkdown(data));
  const webFiles = fs.existsSync(path.join(WEB_DIR, 'index.html')) ? buildWeb() : [];
  if (!quiet) {
    if (webFiles.length) console.log(`Wrote tools/web/norsund/ (${webFiles.length} engine modules) and tools/web/artifact.html`);
    console.log(`Wrote ${path.relative(REPO_ROOT, OUT_JSON)} (${(fs.statSync(OUT_JSON).size / 1024).toFixed(0)} KB, ${data.dictionary.entries.length} entries)`);
    console.log(`Wrote ${path.relative(REPO_ROOT, OUT_DICT)} and ${path.relative(REPO_ROOT, OUT_INDEX)}`);
    console.log(formatReport(report).split('\n').pop());
  }
  return { data, report };
}

if (import.meta.url === `file://${process.argv[1]}` || process.argv[1].endsWith('build.mjs')) build();
